def run_acknowledged_simulation(params, output_filename):
    """Runs the acknowledged protocol simulation and saves a GIF."""
    random.seed(AckSimConfig.RANDOM_SEED)
    p = AckSimConfig.get_params()
    num_stations = params.get("num_nodes", 5)
    p.update({'num_stations': num_stations, 'sender_id': 0,
             'receiver_id': num_stations - 1})
    stats = collections.defaultdict(int)
    env = simpy.Environment()
    ether = AckEther(env)
    for i in range(p['num_stations']):
        ether.pipes[i] = simpy.Store(env)
    viz = AckVisualizer(p['num_stations'], params.get(
        "protocol", "Acknowledged Proto"))
    stations = [AckStation(env, i, ether, p, stats, viz)
                for i in range(p['num_stations'])]
    while stats['acks_received'] < AckSimConfig.TOTAL_DATA_PACKETS and env.now < AckSimConfig.SIM_DURATION_S:
        env.run(until=env.now + (1/60.0))
        viz.draw(env, ether)
    viz.save_gif(output_filename, fps=30)
    print(f"   -> Acknowledged protocol GIF saved to: {output_filename}")


def run_contention_simulation(params, output_filename):
    """Runs the basic contention simulation and saves a GIF."""
    random.seed(ContentionConfig.RANDOM_SEED)
    sim_params = {
        'propagation_delay_s': ContentionConfig.ETHER_LENGTH_M / ContentionConfig.PROPAGATION_SPEED_M_S,
        'mean_arrival_s': 1.0 / params.get("arrival_rate", 10.0),
        'packet_tx_time_s': params.get("data_size", 1024) * 8 / params.get("bandwidth_bps", 1e7),
        'jam_tx_time_s': ContentionConfig.JAM_SIGNAL_BITS / params.get("bandwidth_bps", 1e7)
    }
    sim_params['slot_time_s'] = 2 * sim_params['propagation_delay_s']
    env = simpy.Environment()
    ether = ContentionEther(env)
    num_stations = params.get("num_nodes", 10)
    viz = ContentionVisualizer(num_stations, params.get("protocol", "CSMA/CD"))
    stations = [ContentionStation(env, i, ether, sim_params, viz)
                for i in range(num_stations)]
    time_step = 1/60.0
    while env.now < ContentionConfig.SIM_DURATION_S:
        env.run(until=env.now + time_step)
        viz.draw(env, ether)
    viz.save_gif(output_filename, fps=30)
    print(f"   -> Contention GIF saved to: {output_filename}")


def load_and_parse_logs(log_path):
    log_data = []
    try:
        with open(log_path, 'r') as f:
            file_content = f.read()
            decoder = json.JSONDecoder()
            pos = 0
            while pos < len(file_content.strip()):
                obj, end_pos = decoder.raw_decode(file_content, pos)
                log_data.extend(obj if isinstance(obj, list) else [obj])
                pos = end_pos
                while pos < len(file_content) and file_content[pos].isspace():
                    pos += 1
    except Exception as e:
        print(f"Error parsing {log_path}: {e}")
        return None
    sim_params = next((item.get("params", {}) for item in log_data if isinstance(
        item, dict) and item.get("event") == "simulation_start"), {})
    protocol_name = next((item.get("protocol", "Unknown") for item in log_data if isinstance(
        item, dict) and item.get("event") == "simulation_start"), "Unknown")
    sim_params["protocol"] = protocol_name
    tx_events, intervals, node_stats, active_transmissions, packet_timeline_events = defaultdict(
        dict), [], defaultdict(lambda: {'success': 0, 'failure': 0}), [], []
    for event in log_data:
        if not isinstance(event, dict):
            continue
        event_type, pkt_id, node_id, time = event.get("event"), event.get(
            "pkt_id"), event.get("src"), event.get("time")
        if event_type == "start_tx":
            if pkt_id:
                tx_events[pkt_id].update(
                    {'start': time, 'src': node_id, 'data': event})
            active_transmissions.append((time, 1))
        elif event_type == "end_tx" and pkt_id and 'start' in tx_events[pkt_id]:
            start_time, src_node, start_data = tx_events[pkt_id]['start'], tx_events[pkt_id].get(
                'src'), tx_events[pkt_id].get('data', {})
            duration, success = time - start_time, event.get("success", False)
            if src_node:
                intervals.append((src_node, start_time, duration, success))
                node_stats[src_node]['success' if success else 'failure'] += 1
            packet_timeline_events.append(({"src": src_node, "dst": start_data.get("dst"), "type": start_data.get("type", "PKT"), "seq": start_data.get(
                "seq"), "ack": start_data.get("ack"), "color": start_data.get("color", "#5E81AC")}, start_time, duration, success))
            del tx_events[pkt_id]
            active_transmissions.append((time, -1))
    return {"protocol_name": protocol_name, "sim_params": sim_params, "active_transmissions": sorted(active_transmissions), "intervals": intervals, "node_stats": node_stats, "packet_timeline": packet_timeline_events}


def create_static_visualizations(data, log_filename):
    if not data or not any([data['active_transmissions'], data['intervals'], data['node_stats'], data['packet_timeline']]):
        return None
    protocol_name = data['protocol_name']
    fig, (ax1, ax2, ax3, ax4, ax5) = plt.subplots(5, 1, figsize=(16, 22),
                                                  sharex=True, gridspec_kw={'height_ratios': [1, 2, 1, 2, 2]})
    fig.suptitle(
        f'Daedaelus Simulation Analysis: {protocol_name}\nLog File: {os.path.basename(log_filename)}', fontsize=16)
    if data['active_transmissions']:
        times, deltas = zip(*data['active_transmissions'])
        ax1.step(times, np.cumsum(deltas), where='post', color='#5E81AC')
    ax1.set_title("Medium Contention Timeline")
    ax1.set_ylabel("Active Transmissions")
    ax1.grid(True, linestyle='--', alpha=0.6)
    if data['intervals']:
        nodes = sorted(list(set([i[0] for i in data['intervals']])))
        node_map = {name: i for i, name in enumerate(nodes)}
        for node, start, dur, ok in data['intervals']:
            if node in node_map:
                ax2.broken_barh([(start, dur)], (node_map[node] - 0.4, 0.8),
                                facecolors='#A3BE8C' if ok else '#BF616A')
        if nodes:
            ax2.set_yticks(range(len(nodes)))
            ax2.set_yticklabels(nodes)
            ax2.set_ylim(-0.5, len(nodes) - 0.5)
    ax2.set_title("Per-Node Transmission Events")
    ax2.set_ylabel("Node ID")
    ax2.grid(True, axis='x', linestyle='--', alpha=0.6)
    if data['node_stats']:
        names = sorted(data['node_stats'].keys())
        x = np.arange(len(names))
        ax3.bar(x - 0.2, [data['node_stats'][n]['success']
                for n in names], 0.4, label='Success', color='#A3BE8C')
        ax3.bar(x + 0.2, [data['node_stats'][n]['failure']
                for n in names], 0.4, label='Failure', color='#BF616A')
        ax3.set_xticks(x)
        ax3.set_xticklabels(names, rotation=45, ha="right")
    ax3.set_title("Per-Node Transmission Outcomes")
    ax3.set_ylabel("Packet Count")
    ax3.legend()
    ax3.grid(True, axis='y', linestyle='--', alpha=0.6)
    lanes = sorted(list(set(f"{e['src']}->{e['dst']}" for e, _,
                   _, _ in data['packet_timeline'] if e['src'] and e['dst'])))
    lane_map = {name: i for i, name in enumerate(lanes)}
    for ax, title, use_pkt_color in [(ax4, "Step-by-Step Daedaelus Token Timeline", True), (ax5, "Step-by-Step TCP-Style Packet Timeline", False)]:
        if data['packet_timeline']:
            for pkt_info, start, dur, ok in data['packet_timeline']:
                direction = f"{pkt_info['src']}->{pkt_info['dst']}"
                if direction in lane_map:
                    color = (pkt_info['color'] if use_pkt_color and ok else (
                        '#A3BE8C' if ok else '#BF616A'))
                    ax.broken_barh([(start, dur)], (lane_map[direction] -
                                   0.3, 0.6), facecolors=color, edgecolor='k', lw=0.5)
                    label = f"{pkt_info['type']}[{pkt_info.get('seq') if pkt_info.get('seq') is not None else pkt_info.get('ack', '')}]"
                    ax.text(start + dur/2, lane_map[direction], label, ha='center', va='center',
                            color='w' if not use_pkt_color else 'k', fontsize=8, weight='bold')
            if lanes:
                ax.set_yticks(range(len(lanes)))
                ax.set_yticklabels(lanes)
                ax.set_ylim(-0.5, len(lanes) - 0.5)
        ax.set_title(title)
        ax.set_ylabel("Communication Lane")
        ax.grid(True, linestyle='--', alpha=0.6)
    ax5.set_xlabel("Time (seconds)")
    for ax in [ax1, ax2, ax3, ax4, ax5]:
        ax.spines['top'].set_visible(False)
        ax.spines['right'].set_visible(False)
    plt.tight_layout(rect=[0, 0.03, 1, 0.96])
    return fig

def main():
    """Main execution function to find, visualize, and save all logs and GIFs."""
    os.environ['PYGAME_HIDE_SUPPORT_PROMPT'] = "1"
    parser = argparse.ArgumentParser(
        description="Daedaelus Log Visualizer", formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("log_directory", nargs='?',
                        default="Logs", help="Path to the log directory.")
    args = parser.parse_args()

    log_dir, plot_root_dir = args.log_directory, "plots"
    if not os.path.isdir(log_dir):
        return print(f"Error: Log directory not found at '{log_dir}'")
    found_logs = [os.path.join(r, f) for r, _, files in os.walk(
        log_dir) for f in files if f.endswith(".json")]
    if not found_logs:
        return print(f"No .json logs found in '{log_dir}'.")
    print(f"Found {len(found_logs)} log files. Generating plots and GIFs...")
    os.makedirs(plot_root_dir, exist_ok=True)

    for log_path in found_logs:
        print(f"\n--- Processing: {log_path} ---")
        parsed_data = load_and_parse_logs(log_path)
        if parsed_data:
            relative_path = os.path.relpath(log_path, log_dir)
            plot_dir = os.path.join(
                plot_root_dir, os.path.dirname(relative_path))
            os.makedirs(plot_dir, exist_ok=True)
            base_name = os.path.basename(relative_path).replace('.json', '')
            fig = create_static_visualizations(parsed_data, log_path)
            if fig:
                plot_filename = os.path.join(plot_dir, f"plot_{base_name}.png")
                print(f"   -> Saving static plot to: {plot_filename}")
                fig.savefig(plot_filename, bbox_inches='tight', dpi=150)
                plt.close(fig)
            sim_params = parsed_data.get("sim_params", {})
            if sim_params:
                proto = sim_params.get("protocol", "").lower()
                if 'aloha' in proto or 'metcalfe' in proto or 'contention' in proto:
                    gif_filename = os.path.join(
                        plot_dir, f"contention_{base_name}.gif")
                    try:
                        run_contention_simulation(sim_params, gif_filename)
                    except Exception as e:
                        print(f"   -> FAILED contention GIF: {e}")
                        pygame.quit()
                if 'tcp' in proto or 'duplex' in proto or 'fibre' in proto or 'daedaelus' in proto:
                    gif_filename = os.path.join(
                        plot_dir, f"acknowledged_{base_name}.gif")
                    try:
                        run_acknowledged_simulation(sim_params, gif_filename)
                    except Exception as e:
                        print(f"   -> FAILED acknowledged GIF: {e}")
                        pygame.quit()
    print(
        f"\nAll visualizations have been saved to the '{plot_root_dir}' directory.")

if __name__ == "__main__":
    main()
