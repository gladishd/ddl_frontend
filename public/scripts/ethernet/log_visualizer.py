# --- Contention Simulation Components ---


class ContentionConfig:
    SIM_DURATION_S = 0.05
    RANDOM_SEED = 42
    PROPAGATION_SPEED_M_S = 2e8
    ETHER_LENGTH_M = 500
    JAM_SIGNAL_BITS = 32
    SCREEN_WIDTH, SCREEN_HEIGHT = 800, 300
    STATION_COLOR, IDLE_COLOR = (200, 200, 200), (100, 100, 255)
    TRANSMIT_COLOR, COLLISION_COLOR, JAM_COLOR = (
        100, 255, 100), (255, 100, 100), (255, 150, 50)
    PACKET_HEIGHT = 15


class ContentionPacket:
    def __init__(self, source_id): self.source_id = source_id


class ContentionEther:
    def __init__(self, env):
        self.env = env
        self.transmitting_stations = {}
        self.is_jammed = False

    def is_busy(self): return bool(self.transmitting_stations)
    def has_collision(self): return len(self.transmitting_stations) > 1


class ContentionStation:
    def __init__(self, env, station_id, ether, params, viz):
        self.env, self.id, self.ether, self.params, self.viz = env, station_id, ether, params, viz
        self.packet_queue = simpy.Store(env)
        self.collisions = 0
        self.env.process(self.packet_generator())
        self.env.process(self.run())

    def packet_generator(self):
        for _ in range(3):
            yield self.env.timeout(random.expovariate(1.0 / self.params['mean_arrival_s']))
            yield self.packet_queue.put(ContentionPacket(self.id))
            if self.viz:
                self.viz.update_station_state(self.id, 'queued')

    def run(self):
        while True:
            pkt = yield self.packet_queue.get()
            if self.viz:
                self.viz.update_station_state(self.id, 'queued')
            yield self.env.process(self.transmit(pkt))

    def transmit(self, pkt):
        while True:
            if not self.ether.is_busy():
                if self.viz:
                    self.viz.update_station_state(self.id, 'transmitting')
                self.ether.transmitting_stations[self.id] = self.env.now
                yield self.env.timeout(self.params['propagation_delay_s'])
                if self.ether.has_collision():
                    if self.viz:
                        self.viz.update_station_state(self.id, 'collision')
                    del self.ether.transmitting_stations[self.id]
                    yield self.env.process(self.handle_collision(pkt))
                    break
                yield self.env.timeout(self.params['packet_tx_time_s'] - self.params['propagation_delay_s'])
                del self.ether.transmitting_stations[self.id]
                self.collisions = 0
                if self.viz:
                    self.viz.update_station_state(self.id, 'idle')
                break
            else:
                if self.viz:
                    self.viz.update_station_state(self.id, 'deferring')
                yield self.env.timeout(self.params['slot_time_s'])

    def handle_collision(self, pkt):
        self.collisions += 1
        self.ether.is_jammed = True
        if self.viz:
            self.viz.trigger_jam()
        yield self.env.timeout(self.params['jam_tx_time_s'])
        self.ether.is_jammed = False
        slots = random.randint(0, (2 ** min(self.collisions, 10)) - 1)
        backoff = slots * self.params['slot_time_s']
        if self.viz:
            self.viz.update_station_state(self.id, f'backoff {slots}')
        if backoff > 0:
            yield self.env.timeout(backoff)
        yield self.packet_queue.put(pkt)


class ContentionVisualizer:
    def __init__(self, num_stations, protocol_name):
        pygame.init()
        self.screen = pygame.display.set_mode(
            (ContentionConfig.SCREEN_WIDTH, ContentionConfig.SCREEN_HEIGHT))
        pygame.display.set_caption(f'Daedaelus Contention: {protocol_name}')
        self.font = pygame.font.Font(None, 20)
        self.station_positions = {i: (int(ContentionConfig.SCREEN_WIDTH * (i + 1) / (
            num_stations + 1)), ContentionConfig.SCREEN_HEIGHT // 2) for i in range(num_stations)}
        self.station_states = {i: {
            'state': 'idle', 'color': ContentionConfig.IDLE_COLOR} for i in range(num_stations)}
        self.jam_animation = 0
        self.frames = []

    def trigger_jam(self): self.jam_animation = 10

    def update_station_state(self, sid, state):
        cmap = {'idle': ContentionConfig.IDLE_COLOR, 'queued': (
            255, 255, 100), 'transmitting': ContentionConfig.TRANSMIT_COLOR, 'collision': ContentionConfig.COLLISION_COLOR, 'deferring': (100, 180, 255)}
        self.station_states[sid]['state'] = state
        self.station_states[sid]['color'] = cmap.get(state, (200, 0, 200))

    def draw(self, env, ether):
        self.screen.fill((10, 20, 30))
        y = ContentionConfig.SCREEN_HEIGHT // 2
        col = ContentionConfig.IDLE_COLOR
        if ether.is_jammed or self.jam_animation > 0:
            col, self.jam_animation = ContentionConfig.JAM_COLOR, self.jam_animation - 1
        elif ether.has_collision():
            col = ContentionConfig.COLLISION_COLOR
        elif ether.is_busy():
            col = ContentionConfig.TRANSMIT_COLOR
        pygame.draw.line(self.screen, col, (50, y),
                         (ContentionConfig.SCREEN_WIDTH - 50, y), 5)
        for i, pos in self.station_positions.items():
            s = self.station_states[i]
            pygame.draw.circle(
                self.screen, ContentionConfig.STATION_COLOR, pos, 12)
            pygame.draw.circle(self.screen, s['color'], pos, 10)
            pygame.draw.line(
                self.screen, ContentionConfig.STATION_COLOR, pos, (pos[0], pos[1]-12), 2)
            id_txt, state_txt = self.font.render(f"S{i}", True, (255, 255, 255)), self.font.render(
                s['state'].split()[0], True, s['color'])
            self.screen.blit(id_txt, (pos[0]-id_txt.get_width()//2, pos[1]+15))
            self.screen.blit(
                state_txt, (pos[0]-state_txt.get_width()//2, pos[1]+30))
        for sid, start in ether.transmitting_stations.items():
            x0 = self.station_positions[sid][0]
            prog = min((env.now - start) * ContentionConfig.PROPAGATION_SPEED_M_S /
                       ContentionConfig.ETHER_LENGTH_M, 1.0)
            w = prog * (ContentionConfig.SCREEN_WIDTH - 100) / 2
            pygame.draw.rect(self.screen, col, pygame.Rect(
                x0-w, y-ContentionConfig.PACKET_HEIGHT/2, w, ContentionConfig.PACKET_HEIGHT), border_radius=3)
            pygame.draw.rect(self.screen, col, pygame.Rect(
                x0, y-ContentionConfig.PACKET_HEIGHT/2, w, ContentionConfig.PACKET_HEIGHT), border_radius=3)
        self.screen.blit(self.font.render(
            f"Time: {env.now:.6f}s", True, (255, 255, 255)), (10, 10))
        pygame.display.flip()
        self.frames.append(pygame.surfarray.array3d(
            self.screen).transpose((1, 0, 2)))

    def save_gif(self, filename, fps=30): imageio.mimsave(
        filename, self.frames, fps=fps, loop=0); pygame.quit()

# --- Acknowledged Protocol Simulation Components ---


class AckSimConfig:
    SIM_DURATION_S, RANDOM_SEED = 2.0, 42
    TOTAL_DATA_PACKETS = 10
    RETRANSMISSION_TIMEOUT_S = 0.05
    ETHER_LENGTH_M, PROPAGATION_SPEED_M_S, ETHER_SPEED_BPS = 500, 2e8, 3e6
    DATA_PACKET_BITS, ACK_PACKET_BITS, JAM_SIGNAL_BITS = 4096, 256, 32
    MEAN_BACKGROUND_ARRIVAL_S = 100.0
    SCREEN_WIDTH, SCREEN_HEIGHT = 1000, 400
    DATA_COLOR, ACK_COLOR = (100, 255, 100), (100, 200, 255)
    PACKET_HEIGHT = 15
    STATION_COLOR, IDLE_COLOR = (200, 200, 200), (100, 100, 255)
    COLLISION_COLOR, JAM_COLOR = (255, 100, 100), (255, 150, 50)

    @staticmethod
    def get_params():
        p = {}
        p['propagation_delay_s'] = AckSimConfig.ETHER_LENGTH_M / \
            AckSimConfig.PROPAGATION_SPEED_M_S
        p['slot_time_s'] = 2 * p['propagation_delay_s']
        p['data_tx_time_s'] = AckSimConfig.DATA_PACKET_BITS / \
            AckSimConfig.ETHER_SPEED_BPS
        p['ack_tx_time_s'] = AckSimConfig.ACK_PACKET_BITS / \
            AckSimConfig.ETHER_SPEED_BPS
        p['jam_tx_time_s'] = AckSimConfig.JAM_SIGNAL_BITS / \
            AckSimConfig.ETHER_SPEED_BPS
        return p


class AckPacket:
    def __init__(self, ptype, seq, ack, src, dst):
        self.ptype, self.seq_num, self.ack_num = ptype, seq, ack
        self.source_id, self.destination_id = src, dst
        self.color = AckSimConfig.DATA_COLOR if ptype == 'DATA' else AckSimConfig.ACK_COLOR


class AckEther:
    def __init__(self, env):
        self.env = env
        self.transmitting_stations = {}
        self.is_jammed = False
        self.pipes = {}

    def is_busy(self): return bool(self.transmitting_stations)
    def has_collision(self): return len(self.transmitting_stations) > 1

    def broadcast(self, sender_id, packet):
        for sid, pipe in self.pipes.items():
            if sid != sender_id:
                pipe.put(packet)


class AckStation:
    def __init__(self, env, station_id, ether, params, stats, viz):
        self.env, self.id, self.ether, self.params, self.stats, self.viz = env, station_id, ether, params, stats, viz
        self.is_sender = (station_id == params['sender_id'])
        self.is_receiver = (station_id == params['receiver_id'])
        self.packet_queue = simpy.Store(env)
        self.collisions = 0
        if self.is_sender:
            self.unacked_seq = -1
            self.retx_proc = None
        if self.is_receiver:
            self.expected_seq_num = 0
        env.process(self.packet_generator())
        env.process(self.receiver_logic())
        env.process(self.sender_logic())

    def packet_generator(self):
        if self.is_sender:
            for i in range(AckSimConfig.TOTAL_DATA_PACKETS):
                yield self.packet_queue.put(AckPacket('DATA', i, -1, self.id, self.params['receiver_id']))
        else:
            while True:
                yield self.env.timeout(random.expovariate(1.0/AckSimConfig.MEAN_BACKGROUND_ARRIVAL_S))
                dest = random.choice(
                    [i for i in range(self.params['num_stations']) if i != self.id])
                yield self.packet_queue.put(AckPacket('DATA', -1, -1, self.id, dest))

    def receiver_logic(self):
        pipe = self.ether.pipes[self.id]
        while True:
            pkt = yield pipe.get()
            if self.is_receiver and pkt.ptype == 'DATA' and pkt.destination_id == self.id:
                if pkt.seq_num == self.expected_seq_num:
                    self.stats['app_packets_received'] += 1
                    self.expected_seq_num += 1
                yield self.packet_queue.put(AckPacket('ACK', -1, pkt.seq_num, self.id, pkt.source_id))
            if self.is_sender and pkt.ptype == 'ACK' and pkt.destination_id == self.id:
                if pkt.ack_num == self.unacked_seq:
                    self.stats['acks_received'] += 1
                    if self.retx_proc and not self.retx_proc.triggered:
                        self.retx_proc.interrupt()
                    self.unacked_seq = -1

    def sender_logic(self):
        while True:
            if self.is_sender and self.unacked_seq != -1:
                yield self.env.timeout(self.params['slot_time_s'])
                continue
            pkt = yield self.packet_queue.get()
            self.collisions = 0
            if self.is_sender and pkt.ptype == 'DATA':
                self.unacked_seq = pkt.seq_num
            yield self.env.process(self.transmit_retx_loop(pkt))

    def transmit_retx_loop(self, pkt):
        while True:
            is_reliable = (self.is_sender and pkt.ptype == 'DATA')
            tx_proc = self.env.process(self.csma_cd_transmit(pkt))
            if not is_reliable:
                yield tx_proc
                return
            self.retx_proc = self.env.timeout(
                AckSimConfig.RETRANSMISSION_TIMEOUT_S)
            res = yield tx_proc | self.retx_proc
            if tx_proc in res:
                return
            self.stats['timeouts'] += 1
            self.collisions = 0
            if not tx_proc.triggered:
                tx_proc.interrupt()

    def csma_cd_transmit(self, pkt):
        tx_time = self.params['data_tx_time_s'] if pkt.ptype == 'DATA' else self.params['ack_tx_time_s']
        try:
            while True:
                if not self.ether.is_busy():
                    if self.viz:
                        self.viz.update_station_state(self.id, 'transmitting')
                    self.ether.transmitting_stations[self.id] = (
                        pkt, self.env.now)
                    yield self.env.timeout(self.params['propagation_delay_s'])
                    if self.ether.has_collision():
                        if self.viz:
                            self.viz.update_station_state(self.id, 'collision')
                        del self.ether.transmitting_stations[self.id]
                        yield self.env.process(self.handle_collision())
                        return
                    yield self.env.timeout(tx_time - self.params['propagation_delay_s'])
                    del self.ether.transmitting_stations[self.id]
                    self.ether.broadcast(self.id, pkt)
                    if self.viz:
                        self.viz.update_station_state(self.id, 'idle')
                        return
                else:
                    if self.viz:
                        self.viz.update_station_state(self.id, 'deferring')
                    yield self.env.timeout(self.params['slot_time_s'])
        except simpy.Interrupt:
            if self.id in self.ether.transmitting_stations:
                del self.ether.transmitting_stations[self.id]

    def handle_collision(self):
        self.stats['collisions'] += 1
        self.collisions += 1
        self.ether.is_jammed = True
        if self.viz:
            self.viz.trigger_jam()
        yield self.env.timeout(self.params['jam_tx_time_s'])
        self.ether.is_jammed = False
        slots = random.randint(0, (2**min(self.collisions, 10))-1)
        if self.viz:
            self.viz.update_station_state(self.id, 'backing off')
        if slots > 0:
            yield self.env.timeout(slots * self.params['slot_time_s'])


